package com.ningen.browser.render;

/**
 * 自研液态玻璃着色器（AGSL）· v2
 *
 * 相比 v1 新增：
 *  · uGhost / uGhostR / uMerge —— 幽灵液滴 + 平滑并集，拖拽时胶囊与落后的小液球之间
 *    会拉出液桥，看起来像一泡水被拉扯、分裂、再合并；
 *  · 光照方向 uLight 现在由重力传感器驱动，高光会随手机倾斜真实移动。
 */
final class GlassShaders {

    static final String BAR = String.join("\n",
        "uniform shader uContent;",
        "uniform float2 uSize;",
        "uniform float uCorner;",
        "uniform float2 uPillCenter;",
        "uniform float2 uPillHalf;",
        "uniform float uPillCorner;",
        "uniform float2 uGhost;",
        "uniform float uGhostR;",
        "uniform float uMerge;",
        "uniform float uBulge;",
        "uniform float2 uBulgePos;",
        "uniform float uBulgeR;",
        "uniform float uBlur;",
        "uniform float uLens;",
        "uniform float uChroma;",
        "uniform float uLight;",
        "uniform float uGlow;",
        "uniform float2 uTouch;",
        "uniform float3 uTint;",
        "uniform float uSat;",
        "uniform float uShrink;",
        "uniform float uSheen;",
        "",
        "float sdfRoundBox(float2 p, float2 h, float r) {",
        "    float2 q = abs(p) - h + float2(r, r);",
        "    return length(max(q, float2(0.0, 0.0))) + min(max(q.x, q.y), 0.0) - r;",
        "}",
        "",
        "float smoothMin(float a, float b, float k) {",
        "    float h = clamp(0.5 + 0.5 * (b - a) / k, 0.0, 1.0);",
        "    return mix(b, a, h) - k * h * (1.0 - h);",
        "}",
        "",
        "float sdPill(float2 p) {",
        "    float2 ph = uPillHalf - float2(1.0, 1.0);",
        "    return sdfRoundBox(p - uPillCenter, ph, uPillCorner);",
        "}",
        "",
        "// 液体总轮廓：胶囊 ∪ 拖拽膨胀球 ∪ 落后液滴，全部用平滑并集焊在一起",
        "float sdLiquid(float2 p) {",
        "    float d = sdPill(p);",
        "    if (uBulgeR > 0.6) {",
        "        d = smoothMin(d, length(p - uBulgePos) - uBulgeR, max(2.5, uBulgeR * 0.62));",
        "    }",
        "    if (uGhostR > 0.5) {",
        "        d = smoothMin(d, length(p - uGhost) - uGhostR, max(1.0, uMerge));",
        "    }",
        "    return d;",
        "}",
        "",
        "float4 blur9(float2 p, float r) {",
        "    float4 c0 = float4(uContent.eval(p));",
        "    if (r < 0.75) { return c0; }",
        "    float4 acc = c0 * 4.0;",
        "    acc += float4(uContent.eval(p + float2(-r, 0.0))) * 2.0;",
        "    acc += float4(uContent.eval(p + float2( r, 0.0))) * 2.0;",
        "    acc += float4(uContent.eval(p + float2(0.0, -r))) * 2.0;",
        "    acc += float4(uContent.eval(p + float2(0.0,  r))) * 2.0;",
        "    acc += float4(uContent.eval(p + float2(-r, -r)));",
        "    acc += float4(uContent.eval(p + float2( r, -r)));",
        "    acc += float4(uContent.eval(p + float2(-r,  r)));",
        "    acc += float4(uContent.eval(p + float2( r,  r)));",
        "    return acc * (1.0 / 16.0);",
        "}",
        "",
        "half4 main(float2 fc) {",
        "    // 泡泡形变：移动/按压时胶囊中部鼓起，两端保持圆头",
        "    float2 p = fc;",
        "    float2 rel = fc - uPillCenter;",
        "    float ksw = clamp(1.0 - abs(rel.x) / max(1.0, uPillHalf.x), 0.0, 1.0);",
        "    p.y = uPillCenter.y + rel.y * (1.0 + 0.060 * uSheen * ksw * ksw);",
        "    float2 c = uSize * 0.5;",
        "    float2 hb = c - float2(1.0, 1.0);",
        "    float dBar = sdfRoundBox(fc - c, hb, uCorner);",
        "    float mask = 1.0 - smoothstep(-1.0, 1.0, dBar);",
        "",
        "    float e = 1.6;",
        "    float dxb = sdfRoundBox(fc + float2(e, 0.0) - c, hb, uCorner) - dBar;",
        "    float dyb = sdfRoundBox(fc + float2(0.0, e) - c, hb, uCorner) - dBar;",
        "    float2 nb = normalize(float2(dxb, dyb) + float2(0.0001, 0.0001));",
        "    float band = max(18.0, uCorner * 1.25);",
        "    float tb = clamp(1.0 + dBar / band, 0.0, 1.0);",
        "    float bendB = pow(tb, 2.0);",
        "",
        "    float dLiquid = sdLiquid(p);",
        "",
        "    float dxp = sdLiquid(p + float2(e, 0.0)) - dLiquid;",
        "    float dyp = sdLiquid(p + float2(0.0, e)) - dLiquid;",
        "    float2 np = normalize(float2(dxp, dyp) + float2(0.0001, 0.0001));",
        "    float tp = clamp(1.0 + dLiquid / max(12.0, uPillHalf.y * 0.65), 0.0, 1.0);",
        "    float bendP = pow(tp, 2.4);",
        "",
        "    float2 off = nb * (uLens * bendB) + np * (uLens * 0.85 * bendP);",
        "",
        "    float pillIn = 1.0 - smoothstep(-1.6, 1.6, dLiquid);",
        "    float2 sp = (p - uPillCenter) * (1.0 + uShrink * pillIn) + uPillCenter;",
        "    float2 q2 = sp + off;",
        "    float br = uBlur * (1.0 - 0.94 * pillIn);",
        "",
        "    float4 col;",
        "    col.r = blur9(q2 + off * uChroma, br).r;",
        "    col.g = blur9(q2, br).g;",
        "    col.b = blur9(q2 - off * uChroma, br).b;",
        "    col.a = 1.0;",
        "",
        "    float lum = dot(col.rgb, float3(0.2126, 0.7152, 0.0722));",
        "    col.rgb = mix(float3(lum, lum, lum), col.rgb, uSat);",
        "",
        "    float frost = (0.10 + 0.22 * bendB + 0.16 * bendP) * (1.0 - 0.78 * pillIn);",
        "    col.rgb = mix(col.rgb, uTint, clamp(frost, 0.0, 0.88));",
        "",
        "    float2 q = (p - c) / max(c, float2(1.0, 1.0));",
        "    col.rgb *= 1.0 - 0.10 * clamp(q.y, 0.0, 1.0);",
        "    col.rgb *= 1.0 - 0.05 * clamp(-q.y, 0.0, 1.0);",
        "",
        "    float2 L = normalize(float2(cos(uLight), sin(uLight)));",
        "    float rimBar = 1.0 - smoothstep(0.0, 2.2, abs(dBar + 1.4));",
        "    float facing = max(dot(nb, L), 0.0);",
        "    col.rgb += float3(1.0, 0.99, 0.97) * rimBar * (0.14 + 0.72 * pow(facing, 2.0));",
        "",
        "    float rimPill = 1.0 - smoothstep(0.0, 2.0, abs(dLiquid + 1.2));",
        "    float facingP = max(dot(np, L), 0.0);",
        "    col.rgb += float3(1.0) * rimPill * (0.08 + 0.34 * pow(facingP, 2.0));",
        "    col.rgb += float3(0.05, 0.06, 0.075) * (1.0 - smoothstep(-8.0, 8.0, dLiquid));",
        "",
        "    // 肥皂泡薄膜虹彩：随移动速度/鼓胀增强，沿边缘与法线方向摊开色带",
        "    float filmBand = 1.0 - smoothstep(0.0, max(10.0, uPillHalf.y * 0.95), abs(dLiquid + uPillHalf.y * 0.42));",
        "    float3 spec = 0.5 + 0.5 * cos(6.28318 * (float3(0.0, 0.33, 0.67) + tp * 1.35 + dot(np, L) * 0.28));",
        "    col.rgb = mix(col.rgb, col.rgb * 0.84 + spec * 0.40, filmBand * uSheen * 0.52);",
        "",
        "    // 胀大处的水球张力：向心亮斑 + 更强的高光聚焦",
        "    float bd = length(p - uBulgePos);",
        "    float bulgeGlow = exp(-bd * bd / max(120.0, uBulgeR * uBulgeR * 0.45)) * uBulge;",
        "    col.rgb += float3(0.86, 0.97, 1.0) * bulgeGlow * 0.085;",
        "",
        "    float2 dt = p - uTouch;",
        "    float halo = exp(-dot(dt, dt) / 4200.0) * uGlow;",
        "    col.rgb += float3(1.0, 0.95, 0.88) * halo * 0.30;",
        "",
        "    return half4(float4(col.rgb, mask));",
        "}");

    private GlassShaders() {
    }
}
